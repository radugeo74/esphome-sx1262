#!/usr/bin/env python3
"""Generate a C++ header containing selected upstream wmbusmeters XMQ drivers.
This is a source-embedding prototype, NOT an XMQ/IXML decoder.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[1]
DRIVERS = ROOT / "drivers"
DEFAULT_OUTPUT = ROOT / "generated" / "embedded_xmq_drivers.h"

def read_drivers(directory):
    result = []
    for path in sorted(directory.glob("*.xmq")):
        content = path.read_text(encoding="utf-8")
        match = re.search(r"(?m)^\s*name\s*=\s*([a-zA-Z0-9_]+)\s*$", content)
        if not match or match.group(1) != path.stem:
            raise ValueError(f"{path}: driver name missing/mismatched")
        tests = re.findall(r"(?m)^\s*telegram\s*=\s*([0-9a-fA-F_]+)", content)
        if not tests:
            raise ValueError(f"{path}: no upstream test telegrams")
        result.append((path.stem, content, tests))
    if not result:
        raise ValueError(f"No .xmq drivers in {directory}")
    return result

def make_header(drivers):
    lines = [
        "// Generated by tools/embed_drivers.py; do not edit.",
        "#pragma once",
        "#include <cstddef>",
        "namespace esphome { namespace wmbus_xmq_experimental {",
        "struct EmbeddedDriver { const char *name; const char *source; std::size_t size; };",
    ]
    for name, content, _ in drivers:
        delimiter = "WMBUS_XMQ"
        while ")" + delimiter + "\"" in content:
            delimiter += "_X"
        lines.append(f'static const char driver_{name}[] = R"{delimiter}({content}){delimiter}";')
    lines.append("static const EmbeddedDriver drivers[] = {")
    for name, _, _ in drivers:
        lines.append(f'  {{"{name}", driver_{name}, sizeof(driver_{name}) - 1}},')
    lines += [
        "};",
        "static constexpr std::size_t driver_count = sizeof(drivers) / sizeof(drivers[0]);",
        "}} // namespace esphome::wmbus_xmq_experimental",
        "",
    ]
    return "\n".join(lines)

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    drivers = read_drivers(DRIVERS)
    header = make_header(drivers)
    if args.check:
        if not args.out.exists() or args.out.read_text(encoding="utf-8") != header:
            raise SystemExit("Generated header absent/stale")
    else:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(header, encoding="utf-8")
    for name, content, tests in drivers:
        print(f"{name}: {len(content.encode('utf-8'))} source bytes, {len(tests)} fixtures, sha256={hashlib.sha256(content.encode()).hexdigest()[:16]}")
    print(f"Header {'checked' if args.check else 'written'}: {args.out}")

if __name__ == "__main__":
    main()
