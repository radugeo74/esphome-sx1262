#include <cassert>
#include <cstdint>
#include "../../../components/wmbus_radio/pure_frame_header.h"

// CRC-stripped DLL examples: CI A0 Techem heat and CI A2 Techem water.
// Verify that the independent reader preserves the opaque application span.
int main() {
  const uint8_t heat[] = {
    0x32,0x44,0x68,0x50,0x67,0x30,0x27,0x24,0x69,0x80,0xA0,
    0x11,0x3E,0x35,0x01,0x00,0xD0,0x15,0x00,0x00,0x92,0x08,0x98,0x08,
    0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
    0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x01,0x00,0x00,0x00,
    0x00
  };
  wmbus_pure::Header h{};
  assert(wmbus_pure::parse_header(heat, sizeof(heat), h) == wmbus_pure::HeaderStatus::Ok);
  assert(h.ci == 0xA0 && h.meter_id == 24273067);
  assert(h.application == heat + 11 && h.application_length == sizeof(heat) - 11);
  assert(h.application[0] == 0x11);
  const uint8_t water[] = {
    0x2F,0x44,0x68,0x50,0x20,0x01,0x41,0x02,0x95,0x62,0xA2,
    0x06,0x70,0x29,0x01,0x00,0x60,0x17,0x03,0x00,0x04,0x00,0x03,
    0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
    0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
    0x00,0x00
  };
  assert(wmbus_pure::parse_header(water, sizeof(water), h) == wmbus_pure::HeaderStatus::Ok);
  assert(h.ci == 0xA2 && h.application[0] == 0x06);
  assert(h.application_length == sizeof(water) - 11);
  uint8_t malformed[sizeof(water)]{};
  for (size_t i=0;i<sizeof(water);++i) malformed[i]=water[i];
  malformed[0]=0x10;
  assert(wmbus_pure::parse_header(malformed,sizeof(malformed),h)==wmbus_pure::HeaderStatus::InvalidLength);
  assert(h.application==nullptr);
}
